#!/usr/bin/env node
/**
 * Re-derives the ORIGINAL GayDex battle engine from the pristine artifact
 * (`tests/fixtures/original-single-file.html`, which came straight out of
 * `git show cbbe7a3:GayDex_Battle_Simulator_SINGLE_FILE.html`) and writes it as
 * a Node-loadable test fixture.
 *
 * Provenance matters here: the fixture is *generated from the original code*,
 * never hand-copied.  `tests/battle-equivalence.test.mjs` then runs the
 * refactored `src/battle-core.js` against it over many seeds and settings, and
 * fails on any divergence.  That is how the refactor proves it did not change
 * battle truth.
 *
 * Run: node tools/extract-original-engine.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const app = readFileSync(join(ROOT, 'src/app.js'), 'utf8');
const pristine = readFileSync(join(ROOT, 'tests/fixtures/original-single-file.html'), 'utf8');

// The pristine app.js is embedded between the first "<script>" and the last
// "</script>" of the pristine artifact; recover it independently of src/app.js
// so the fixture can never inherit a later edit.
const s = pristine.indexOf('<script>') + '<script>'.length;
const e = pristine.lastIndexOf('</script>');
const pristineApp = pristine.slice(s, e);
if (pristineApp !== '\n' + app + '\n' && pristineApp.trim() !== app.trim()) {
  console.warn('note: src/app.js has drifted from pristine (expected once Circuit work lands)');
}

const lines = pristineApp.split('\n');

/** Collect a top-level declaration by name, following brace/paren balance. */
function grab(name) {
  const prefixes = [`function ${name}(`, `const ${name}=`, `const ${name} =`, `let ${name}=`];
  let i = lines.findIndex((l) => prefixes.some((p) => l.startsWith(p)));
  if (i < 0) throw new Error(`cannot find top-level declaration: ${name}`);
  let text = lines[i];
  let depth = 0;
  for (const ch of text) if (ch === '{' || ch === '(') depth++; else if (ch === '}' || ch === ')') depth--;
  // Single-line statements dominate this file; keep consuming until balanced
  // and terminated, so multi-line declarations also survive.
  while (depth > 0 || !/[;}\n]$/.test(text.trimEnd())) {
    i++;
    if (i >= lines.length) throw new Error(`unbalanced declaration: ${name}`);
    text += '\n' + lines[i];
    for (const ch of lines[i]) if (ch === '{' || ch === '(') depth++; else if (ch === '}' || ch === ')') depth--;
  }
  return text;
}

const TABLES = ['BATTLE_LINES', 'BATTLE_MOVES', 'BATTLE_COUNTER', 'BATTLE_SCENE_RULES', 'BATTLE_PULSE_FORECAST', 'BATTLE_OPENER_RULES'];
const FUNCS = [
  'moveThatBeats', 'sceneRule', 'resolvedBattleOpener', 'applyBattleOpener',
  'battleArenaPulse',
  'hashSeed', 'seededRng', 'battleStats', 'stagePassive', 'lineagePassive', 'signatureSpec',
  'makeFighter', 'makeBattleMatch', 'attackValue', 'counterMultiplier', 'battleMoveMeta',
  'actionInitiative', 'applyAttack', 'battleRound', 'aiBattleMove', 'chooseCpuBattleMove',
  'simulateBattle',
];

const collected = [...TABLES.map(grab), ...FUNCS.map(grab)];

const fixture = `/* GENERATED by tools/extract-original-engine.mjs — do not edit.
 * Source of truth: git show cbbe7a32f557f5a4e30424b8df35a79b82a2cf6e:GayDex_Battle_Simulator_SINGLE_FILE.html
 * These are the ORIGINAL engine declarations, verbatim, with only the DOM-free
 * \`battleState\` stub supplied by this file. Used as the golden reference for
 * tests/battle-equivalence.test.mjs. */
'use strict';
const battleState = {
  scene: 'prism', intro: 'sweep', arenaEffects: true, balanced: true, cpuSkill: 'rival',
  cpuB: false, speed: 1.5, moveA: 'flex', moveB: 'serve', idA: 'twink', idB: 'cub',
  lineA: 'Twink', lineB: 'Cub',
};

${collected.join('\n')}

module.exports = {
  battleState,
${[...TABLES, ...FUNCS].map((n) => `  ${n},`).join('\n')}
};
`;

writeFileSync(join(ROOT, 'tests/fixtures/original-engine.cjs'), fixture);
console.log(`wrote tests/fixtures/original-engine.cjs (${fixture.length} bytes, ${TABLES.length} tables + ${FUNCS.length} functions)`);

/* ---- canonical GayDex entries ------------------------------------------
 * Also derived from the pristine artifact, with the base64 portraits stripped
 * (irrelevant to battle math).  Tests read this instead of parsing app.js, so
 * the canonical taxonomy under test can never drift with UI work. */
const dexEnd = pristineApp.indexOf('const COLORS');
const dexSrc = pristineApp.slice(0, dexEnd).replace(/^\s*const GAYDEX=/, '').replace(/;\s*$/, '');
const GAYDEX = new Function(`return (${dexSrc})`)();
if (!Array.isArray(GAYDEX) || GAYDEX.length !== 19) throw new Error(`unexpected GAYDEX length: ${GAYDEX?.length}`);
const slim = GAYDEX.map(({ img, ...rest }) => ({ ...rest, imgBytes: img.length }));
writeFileSync(join(ROOT, 'tests/fixtures/dex-entries.json'), JSON.stringify(slim, null, 1) + '\n');
console.log(`wrote tests/fixtures/dex-entries.json (${slim.length} canonical entries)`);
